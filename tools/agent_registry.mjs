import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { expandIdPattern } from "../obsidian-plugin/src/agent-id-pattern.mjs";

export const SHELL_REGISTRY = "agent-kinds.zsh";
const registry = new URL("../atlas/agents.json", import.meta.url);

function quote(value) {
  return "'" + value.replaceAll("'", "'\\''") + "'";
}

export function shellRegistry(rows = JSON.parse(fs.readFileSync(registry, "utf8"))) {
  for (const { id } of rows) {
    if (!/^[a-z][a-z0-9-]*$/.test(id)) throw new Error(`Invalid agent ID: ${id}`);
  }
  return [
    "# Generated by tools/agent_registry.mjs from atlas/agents.json.",
    "typeset -gA ATLAS_AGENT_MODULES=(" + rows.map(row => quote(row.id) + " " + quote("agent-" + row.id + ".zsh")).join(" ") + ")",
    "typeset -gA ATLAS_MAIL_PREFIXES=(" + rows.map(row => quote(row.id) + " " + quote(row.mailPrefix)).join(" ") + ")",
    "typeset -gA ATLAS_ID_PATTERNS=(" + rows.map(row => quote(row.id) + " " + quote(expandIdPattern(row.idPattern))).join(" ") + ")",
    "",
  ].join("\n");
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const [, , registryPath] = process.argv;
  process.stdout.write(shellRegistry(registryPath ? JSON.parse(fs.readFileSync(registryPath, "utf8")) : undefined));
}
